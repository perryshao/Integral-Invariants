function I = Moment_Invariant(marker_xyz)

I = zeros(1, 6);
I(1) = Moments(marker_xyz, 4, 0, 0) + Moments(marker_xyz, 0, 4, 0) + Moments(marker_xyz, 0, 0, 4) ...
       + 2 * Moments(marker_xyz, 2, 2, 0) + 2 * Moments(marker_xyz, 2, 0, 2) + 2 * Moments(marker_xyz, 0, 2, 2);
I(1) = I(1) / (Moments(marker_xyz, 0, 0, 0)^3);

I(2) = Moments(marker_xyz, 4, 0, 0) * Moments(marker_xyz, 0, 4, 0) + Moments(marker_xyz, 4, 0, 0) * Moments(marker_xyz, 0, 0, 4) ...
       + Moments(marker_xyz, 0, 0, 4) * Moments(marker_xyz, 0, 4, 0) + 3 * Moments(marker_xyz, 2, 2, 0)^2 + 3 * Moments(marker_xyz, 2, 0, 2)^2. ...
       + 3 * Moments(marker_xyz, 0, 2, 2)^2 - 4 * Moments(marker_xyz, 1, 0, 3) * Moments(marker_xyz, 3, 0, 1) ...
       - 4 * Moments(marker_xyz, 1, 3, 0) * Moments(marker_xyz, 3, 1, 0) - 4 * Moments(marker_xyz, 0, 1, 3) * Moments(marker_xyz, 0, 3, 1) ...
       + 2 * Moments(marker_xyz, 0, 2, 2) * Moments(marker_xyz, 2, 0, 2) + 2 * Moments(marker_xyz, 0, 2, 2) * Moments(marker_xyz, 2, 2, 0) ...
       + 2 * Moments(marker_xyz, 2, 2, 0) * Moments(marker_xyz, 2, 0, 2) + 2 * Moments(marker_xyz, 0, 2, 2) * Moments(marker_xyz, 4, 0, 0) ...
       + 2 * Moments(marker_xyz, 0, 0, 4) * Moments(marker_xyz, 2, 2, 0) + 2 * Moments(marker_xyz, 0, 4, 0) * Moments(marker_xyz, 2, 0, 2) ...
       - 4 * Moments(marker_xyz, 0, 1, 3) * Moments(marker_xyz, 1, 2, 1) - 4 * Moments(marker_xyz, 1, 3, 0) * Moments(marker_xyz, 1, 1, 2) ...
       - 4 * Moments(marker_xyz, 0, 1, 3) * Moments(marker_xyz, 2, 1, 1) - 4 * Moments(marker_xyz, 1, 2, 1) * Moments(marker_xyz, 3, 0, 1) ...
       - 4 * Moments(marker_xyz, 1, 1, 2) * Moments(marker_xyz, 3, 1, 0) - 4 * Moments(marker_xyz, 2, 1, 1) * Moments(marker_xyz, 0, 3, 1) ...
       + 4 * Moments(marker_xyz, 2, 1, 1) * Moments(marker_xyz, 2, 1, 1) + 4 * Moments(marker_xyz, 1, 1, 2) * Moments(marker_xyz, 1, 1, 2) ...
       + 4 * Moments(marker_xyz, 1, 2, 1) * Moments(marker_xyz, 1, 2, 1);
I(2) = I(2) / (Moments(marker_xyz, 0, 0, 0)^6);

I(3) = Moments(marker_xyz, 4, 0, 0)^2 + Moments(marker_xyz, 0, 4, 0)^2 + Moments(marker_xyz, 0, 0, 4)^2 + 4 * Moments(marker_xyz, 1, 3, 0)^2. ...
       + 4 * Moments(marker_xyz, 1, 0, 3)^2 + 4 * Moments(marker_xyz, 0, 1, 3)^2 + 4 * Moments(marker_xyz, 0, 3, 1)^2 + 4 * Moments(marker_xyz, 3, 1, 0)^2. ...
       + 4 * Moments(marker_xyz, 3, 0, 1)^2 + 6 * Moments(marker_xyz, 2, 2, 0)^2 + 6 * Moments(marker_xyz, 2, 0, 2)^2 + 6 * Moments(marker_xyz, 0, 2, 2)^2. ...
       + 12 * Moments(marker_xyz, 1, 1, 2)^2 + 12 * Moments(marker_xyz, 1, 2, 1)^2 + 12 * Moments(marker_xyz, 2, 1, 1)^2;
I(3) = I(3) / (Moments(marker_xyz, 0, 0, 0)^6);

I(4) = Moments(marker_xyz, 3, 0, 0)^2 + Moments(marker_xyz, 0, 3, 0)^2 + Moments(marker_xyz, 0, 0, 3)^2 + 3 * Moments(marker_xyz, 1, 2, 0)^2. ...
       + 3 * Moments(marker_xyz, 1, 0, 2)^2 + 3 * Moments(marker_xyz, 0, 1, 2)^2 + 3 * Moments(marker_xyz, 0, 2, 1)^2 + 3 * Moments(marker_xyz, 2, 1, 0)^2. ...
       + 3 * Moments(marker_xyz, 2, 0, 1)^2 + 6 * Moments(marker_xyz, 1, 1, 1)^2;
I(4) = I(4) / (Moments(marker_xyz, 0, 0, 0)^5);

I(5) = Moments(marker_xyz, 3, 0, 0)^2 + Moments(marker_xyz, 0, 3, 0)^2 + Moments(marker_xyz, 0, 0, 3)^2 + Moments(marker_xyz, 1, 2, 0)^2. ...
       + Moments(marker_xyz, 0, 1, 2)^2 + Moments(marker_xyz, 1, 0, 2)^2 + Moments(marker_xyz, 2, 1, 0)^2 + Moments(marker_xyz, 0, 2, 1)^2. ...
       + Moments(marker_xyz, 2, 0, 1)^2 + 2 * Moments(marker_xyz, 3, 0, 0) * Moments(marker_xyz, 1, 2, 0) + 2 * Moments(marker_xyz, 3, 0, 0) * Moments(marker_xyz, 1, 0, 2) ...
       + 2 * Moments(marker_xyz, 1, 2, 0) * Moments(marker_xyz, 1, 0, 2) + 2 * Moments(marker_xyz, 0, 0, 3) * Moments(marker_xyz, 2, 0, 1) ...
       + 2 * Moments(marker_xyz, 0, 0, 3) * Moments(marker_xyz, 0, 2, 1) + 2 * Moments(marker_xyz, 0, 2, 1) * Moments(marker_xyz, 2, 0, 1) ...
       + 2 * Moments(marker_xyz, 0, 3, 0) * Moments(marker_xyz, 0, 1, 2) + 2 * Moments(marker_xyz, 0, 3, 0) * Moments(marker_xyz, 2, 1, 0) ...
       + 2 * Moments(marker_xyz, 0, 1, 2) * Moments(marker_xyz, 2, 1, 0);

I(5) = I(5) / (Moments(marker_xyz, 0, 0, 0)^5);

I(6) = Moments(marker_xyz, 2, 0, 0) * (Moments(marker_xyz, 4, 0, 0) + Moments(marker_xyz, 2, 2, 0) + Moments(marker_xyz, 2, 0, 2)) ...
       + Moments(marker_xyz, 0, 2, 0) * (Moments(marker_xyz, 2, 2, 0) + Moments(marker_xyz, 0, 4, 0) + Moments(marker_xyz, 0, 2, 2)) ...
       + Moments(marker_xyz, 0, 0, 2) * (Moments(marker_xyz, 2, 0, 2) + Moments(marker_xyz, 0, 2, 2) + Moments(marker_xyz, 0, 0, 4)) ...
       + 2 * Moments(marker_xyz, 1, 1, 0) * (Moments(marker_xyz, 3, 1, 0) + Moments(marker_xyz, 1, 3, 0) + Moments(marker_xyz, 1, 1, 2)) ...
       + 2 * Moments(marker_xyz, 1, 0, 1) * (Moments(marker_xyz, 3, 0, 1) + Moments(marker_xyz, 1, 2, 1) + Moments(marker_xyz, 1, 0, 3)) ...
       + 2 * Moments(marker_xyz, 0, 1, 1) * (Moments(marker_xyz, 2, 1, 1) + Moments(marker_xyz, 0, 3, 1) + Moments(marker_xyz, 0, 1, 3));

I(6) = I(6) / (Moments(marker_xyz, 0, 0, 0)^5);

% I = I/sum(I);
